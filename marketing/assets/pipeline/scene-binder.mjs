import { launch, weddingPage, BASE, settle } from './lib.mjs';
import { Recorder, TOUCH_SCRIPT } from './recorder.mjs';
const b = await launch();
// 13:45 at the venue on the day: the ceremony is on now.
const { page } = await weddingPage(b, { width: 390, height: 844, scale: 3, time: '2028-06-01T13:45:00+01:00', init: TOUCH_SCRIPT });
await page.goto(BASE + '/binder'); await settle(page, 1200);
const r = new Recorder(page, 'work/frames/binder');
r.x = 200; r.y = 600; await page.mouse.move(200, 600);
const nav = page.getByRole('navigation', { name: 'The Binder' });
const tap = async (loc, s = 0.5) => { await r.moveToLocator(loc, s); await page.mouse.down(); await r.frame(1 / 30); await page.mouse.up(); await r.live(0.45); };

r.caption('What’s on now, at the venue');
await r.hold(2.4);
r.caption('The whole running order');
await tap(nav.getByRole('button', { name: 'Day' }));
await r.hold(2.0);
r.caption('Who to ring, one tap away');
await tap(nav.getByRole('button', { name: 'Ring' }));
await r.hold(1.8);
r.caption('Where does Zainab sit?');
await tap(nav.getByRole('button', { name: 'Find' }));
await page.getByRole('searchbox').focus();
await r.type('zainab l', 0.11);
await r.live(0.3);
await r.hold(1.8);
r.caption('The shot list, ticked off');
await tap(nav.getByRole('button', { name: 'Shots' }));
const shots = page.getByRole('region', { name: 'The shot list' }).getByRole('checkbox');
await tap(shots.nth(0), 0.45);
await tap(shots.nth(1), 0.45);
await tap(shots.nth(2), 0.45);
await r.hold(1.4);
r.caption('Works without signal');
await tap(nav.getByRole('button', { name: 'Now' }));
await r.hold(2.2);
r.save();
await b.close();
